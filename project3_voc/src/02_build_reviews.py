def pick_source():
    r = random.random(); acc = 0
    for s, w in SOURCES:
        acc += w
        if r <= acc:
            return s
    return SOURCES[0][0]


def build_text(theme, kind):
    core = random.choice(T[theme][kind])
    text = core.format(pf=random.choice(P), ch=random.choice(CH), n1=random.choice(N1))
    if kind == "neg" and random.random() < 0.55:
        text += random.choice(CONSEQ)
    if kind != "q":
        text = random.choice(PREFIX) + text + random.choice(SUFFIX)
    if random.random() < 0.12:
        text += random.choice(EMO)
    return text


def main(n=850):
    themes, weights = zip(*THEME_W)
    rows = []
    start = date(2025, 3, 1)
    for i in range(n):
        theme = random.choices(themes, weights=weights)[0]
        roll = random.random()
        if theme == "praise":
            kind = "pos" if roll < 0.82 else "neu"
        elif roll < 0.18 and T[theme].get("q"):
            kind = "q"
        elif roll < 0.70:
            kind = "neg"
        elif roll < 0.86:
            kind = "neu"
        else:
            kind = "pos"
        text = build_text(theme, kind)
        rating = {"neg": random.choices([1, 2], [0.6, 0.4])[0],
                  "neu": random.choices([3, 4], [0.7, 0.3])[0],
                  "pos": random.choices([5, 4], [0.8, 0.2])[0],
                  "q": random.choices([3, 4, 5], [0.5, 0.3, 0.2])[0]}[kind]
        rows.append(dict(review_id=f"R{i+1:04d}", source=pick_source(),
                         post_date=(start + timedelta(days=random.randint(0, 183))).isoformat(),
                         rating=rating, theme=theme, theme_name=THEME_NAME[theme],
                         is_question=int(kind == "q"), text=text))

    # 10% 广告
    for j in range(int(n * 0.10)):
        i += 1
        rows.append(dict(review_id=f"R{i+1:04d}", source=pick_source(),
                         post_date=(start + timedelta(days=random.randint(0, 183))).isoformat(),
                         rating="", theme="ad", theme_name="广告灌水", is_question=0,
                         text=random.choice(AD_TEXTS)))
    n0 = len(rows)
    # 8% 完全重复
    for _ in range(int(n * 0.08)):
        src = random.choice(rows[:n0]); dup = src.copy(); i += 1
        dup["review_id"] = f"R{i+1:04d}"
        dup["post_date"] = (date.fromisoformat(dup["post_date"]) + timedelta(days=random.randint(1, 20))).isoformat()
        rows.append(dup)
    # 5% 近似重复
    for _ in range(int(n * 0.05)):
        src = random.choice(rows[:n0]); dup = src.copy(); i += 1
        dup["review_id"] = f"R{i+1:04d}"
        dup["text"] = src["text"] + random.choice(["，同意楼上", "啊", "吧", " 我也遇到了", "。。。"])
        rows.append(dup)

    random.shuffle(rows)
    p = OUT / "reviews_raw.csv"
    with p.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=["review_id", "source", "post_date", "rating",
                                          "theme", "theme_name", "is_question", "text"])
        w.writeheader(); w.writerows(rows)
    q = sum(r["is_question"] for r in rows)
    print(f"[OK] raw reviews: {len(rows)} | questions: {q} | ads: {int(n*0.10)} -> {p}")


if __name__ == "__main__":
    main()

THEME_W = [("logistics", 0.14), ("inventory", 0.13), ("order_sync", 0.10), ("stability", 0.10),
           ("support", 0.08), ("pricing", 0.07), ("onboarding", 0.07), ("finance", 0.06),
           ("listing", 0.05), ("praise", 0.20)]

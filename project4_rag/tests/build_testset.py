def main():
    rows, seen, seen_norm = [], set(), set()
    voc_path = TESTS / "voc_questions.jsonl"
    if voc_path.exists():
        for line in voc_path.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            mod = THEME2MODULE.get(r["theme"])
            nq = norm_q(r["question"])
            if not mod or r["question"] in seen or nq in seen_norm:
                continue  # 同一提问模板的不同平台/渠道变体只保留一条
            seen.add(r["question"])
            seen_norm.add(nq)
            rows.append({"qid": r["qid"], "question": r["question"],
                         "expected_module": mod, "keywords": [], "source": "voc"})
    for qid, q, mod, kws in CURATED:
        if q not in seen:
            seen.add(q)
            rows.append({"qid": qid, "question": q, "expected_module": mod,
                         "keywords": kws, "source": "curated"})
    out = TESTS / "test_questions.jsonl"
    with out.open("w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    by_mod = {}
    for r in rows:
        by_mod[r["expected_module"]] = by_mod.get(r["expected_module"], 0) + 1
    print(f"[OK] testset: {len(rows)} questions -> {out}")
    for m, n in sorted(by_mod.items(), key=lambda x: -x[1]):
        print(f"  - {m}: {n}")


if __name__ == "__main__":
    main()
